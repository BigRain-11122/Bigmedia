class PreflightBehaviorTests(unittest.TestCase):
    """Exec the generated launcher with faked subprocess/time: rc 4/7
    bails write NO e4-result.json; GO path writes the verdict."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix='e4gen_pf_')
        self.saved = {k: sys.modules.get(k) for k in ('subprocess', 'time')}
        self.path = os.path.join(self.tmp, 'e4_call.py')
        self.src = gen.render_launcher(u'E4 body', 'L', 'qwen2.5:14b', 1500)
        with io.open(self.path, 'w', encoding='utf-8') as fh:
            fh.write(self.src)

    def tearDown(self):
        for key, mod in self.saved.items():
            if mod is None:
                sys.modules.pop(key, None)
            else:
                sys.modules[key] = mod

    def _exec(self):
        import contextlib
        buf = io.StringIO()
        code = compile(self.src, self.path, 'exec')
        rc = 0
        ns = {'__file__': self.path, '__name__': 'e4_call_under_test'}
        with contextlib.redirect_stdout(buf):
            try:
                exec(code, ns)
            except SystemExit as exc:
                rc = exc.code
        return rc, buf.getvalue()

    def _install_fakes(self, handler, step=1.0):
        import types
        sub = types.ModuleType('subprocess')
        sub.PIPE = subprocess.PIPE
        sub.STDOUT = subprocess.STDOUT
        sub.TimeoutExpired = subprocess.TimeoutExpired
        sub.run = handler
        tim = types.ModuleType('time')
        state = {'t': 1000000.0}
        tim.time = lambda: (state.__setitem__('t', state['t'] + step)
                            or state['t'])
        tim.strftime = lambda fmt, *a: '2026-10-12 00:00:00'
        sys.modules['subprocess'] = sub
        sys.modules['time'] = tim
        return sub

    def test_flip_bail_rc4_no_result_file(self):
        def handler(cmd, **kw):
            return _FakeProc(stdout=b'99, 4000')  # nvidia-smi util=99
        self._install_fakes(handler)
        rc, out = self._exec()
        self.assertEqual(rc, 4)
        self.assertIn('DEFER window flipped after card', out)
        self.assertIn('PREFLIGHT-BAIL rc=4', out)
        self.assertFalse(os.path.exists(
            os.path.join(self.tmp, 'e4-result.json')))

    def test_slow_seat_bail_rc7_no_result_file(self):
        calls = []

        def handler(cmd, **kw):
            if cmd[0] == 'nvidia-smi':
                return _FakeProc(stdout=b'30, 8000')
            if cmd[:2] == ['ollama', 'ps']:
                return _FakeProc(stdout=b'qwen2.5:14b    abc123    '
                                         b'100% GPU    9.4 GB')
            if cmd[:2] == ['ollama', 'stop']:
                return _FakeProc(stdout=b'')
            if cmd[:2] == ['ollama', 'run']:
                calls.append(kw.get('input'))
                return _FakeProc(stdout=b'OK')
            raise AssertionError(cmd)
        self._install_fakes(handler, step=200.0)  # each time() +200s
        rc, out = self._exec()
        self.assertEqual(rc, 7)
        self.assertIn('RATE-FAIL seat probe 200s > 150s', out)
        self.assertIn('CPU-offload', out)
        # only the seat probe ran; the main 1500s call never launched
        self.assertEqual(calls, [b'Reply with exactly two chars: OK'])
        self.assertFalse(os.path.exists(
            os.path.join(self.tmp, 'e4-result.json')))

    def test_seat_timeout_bail_rc7_no_result_file(self):
        def handler(cmd, **kw):
            if cmd[0] == 'nvidia-smi':
                return _FakeProc(stdout=b'30, 8000')
            if cmd[:2] == ['ollama', 'ps']:
                return _FakeProc(stdout=b'NAME    ID    PROCESSOR')
            if cmd[:2] == ['ollama', 'run']:
                raise subprocess.TimeoutExpired(cmd, 240)
            raise AssertionError(cmd)
        self._install_fakes(handler)
        rc, out = self._exec()
        self.assertEqual(rc, 7)
        self.assertIn('RATE-FAIL seat probe timed out (240s cap', out)
        self.assertFalse(os.path.exists(
            os.path.join(self.tmp, 'e4-result.json')))

    def test_go_path_relief_probe_then_verdict(self):
        calls = []

        def handler(cmd, **kw):
            if cmd[0] == 'nvidia-smi':
                return _FakeProc(stdout=b'25, 9000')
            if cmd[:2] == ['ollama', 'ps']:
                return _FakeProc(stdout=b'qwen2.5:14b    abc123    '
                                         b'100% GPU    9.4 GB')
            if cmd[:2] == ['ollama', 'stop']:
                return _FakeProc(stdout=b'')
            if cmd[:2] == ['ollama', 'run']:
                calls.append(kw.get('input'))
                if kw.get('input') == b'Reply with exactly two chars: OK':
                    return _FakeProc(stdout=b'OK')
                return _FakeProc(stdout=b'7.0\naudience verdict line')
            raise AssertionError(cmd)
        self._install_fakes(handler, step=1.0)
        rc, out = self._exec()
        self.assertEqual(rc, 0)
        self.assertIn('RELIEF stopped idle resident qwen2.5:14b', out)
        self.assertIn('RATE-OK seat probe 1s', out)
        self.assertIn('DONE', out)
        self.assertEqual(len(calls), 2)  # probe + main
        with io.open(os.path.join(self.tmp, 'e4-result.json'), 'r',
                     encoding='utf-8') as fh:
            result = json.load(fh)
        self.assertEqual(result['model'], 'qwen2.5:14b')
        self.assertEqual(result['material'], 'L')
        self.assertIn('7.0', result['verdict'])

    def test_unguarded_when_nvidia_smi_unreadable(self):
        def handler(cmd, **kw):
            if cmd[0] == 'nvidia-smi':
                return _FakeProc(stdout=b'', returncode=1)
            if cmd[:2] == ['ollama', 'run']:
                return _FakeProc(stdout=b'OK\nverdict')
            raise AssertionError(cmd)
        self._install_fakes(handler)
        rc, out = self._exec()
        self.assertEqual(rc, 0)
        self.assertIn('nvidia-smi unreadable - proceeding unguarded', out)
        self.assertTrue(os.path.exists(
            os.path.join(self.tmp, 'e4-result.json')))


class CpuLaneRenderTests(unittest.TestCase):
    """tech#169: --cpu-lane renders the CPU variant -- API flight with
    the zero-GPU-touch assertion (num_gpu=0) + CEO 10% margin
    (num_thread=4), no GPU preflight -- while the GPU template stays
    byte-shaped as before (no CPU markers leak into it)."""

    def _render(self, cpu_lane):
        return gen.render_launcher(u'body text', u'label-x',
                                   u'qwen2.5:14b', 1500, cpu_lane=cpu_lane)

    def test_cpu_variant_carries_cpu_assertions(self):
        src = self._render(True)
        self.assertIn("num_gpu': 0", src)      # zero-GPU-touch assertion
        self.assertIn('CPU_THREADS = 4', src)  # 10% margin law constant
        self.assertIn("num_thread': CPU_THREADS", src)
        self.assertIn('api/generate', src)     # API face (CLI has no
                                               # num_gpu flag, tech#164)
        self.assertIn('CPU LANE', src)
        self.assertIn("LANE = 'cpu'", src)  # result auditability

    def test_cpu_variant_has_no_gpu_faces(self):
        src = self._render(True)
        self.assertNotIn('nvidia-smi', src)            # never touches GPU
        self.assertNotIn('preflight(', src)           # no GPU preflight
        self.assertNotIn("['ollama', 'stop']", src)   # no relief face
        self.assertNotIn('UTIL_FLIP', src)

    def test_gpu_render_regression_no_cpu_markers(self):
        src = self._render(False)
        self.assertNotIn('num_gpu', src)
        self.assertNotIn('num_thread', src)
        self.assertNotIn('CPU LANE', src)
        self.assertIn('preflight(', src)   # GPU three-piece intact
        self.assertIn('nvidia-smi', src)

    def test_no_placeholder_leftovers_either_lane(self):
        for cpu_lane in (True, False):
            src = self._render(cpu_lane)
            for marker in ('__LABEL__', '__MODEL__', '__TIMEOUT__',
                           '__LABEL_REPR__', '__PROMPT_REPR__',
                           '__THREADS__', '__AUTO_LEDGER_BLOCK__'):
                self.assertNotIn(marker, src,
                                  'lane=%s leaked %s' % (cpu_lane, marker))

    def test_cpu_variant_compiles(self):
        compile(self._render(True), 'e4_call_cpu.py', 'exec')

    def test_cli_cpu_lane_flag_writes_cpu_variant(self):
        with tempfile.TemporaryDirectory() as tmp:
            body = os.path.join(tmp, 'e4-body.txt')
            with io.open(body, 'w', encoding='utf-8') as fh:
                fh.write(u'卡面内容叙述。')
            out = os.path.join(tmp, 'e4_call_cpu.py')
            proc = _run_cli('--body', body, '--label', 'L1',
                            '--out', out, '--cpu-lane')
            self.assertEqual(proc.returncode, 0, proc.stdout)
            with io.open(out, encoding='utf-8') as fh:
                src = fh.read()
            self.assertIn("num_gpu': 0", src)
            self.assertIn('CPU LANE', src)


