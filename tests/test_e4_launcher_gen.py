class CliTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix='e4gen_')

    def _write(self, name, text):
        path = os.path.join(self.tmp, name)
        with io.open(path, 'w', encoding='utf-8') as fh:
            fh.write(text)
        return path

    def test_default_out_is_body_dir_e4_call(self):
        body = self._write('body.txt', u'角色+卡面描述+背景叙事。')
        p = _run_cli('--body', body, '--label', 'LABEL-X')
        self.assertEqual(p.returncode, 0, p.stdout.decode('utf-8', 'replace'))
        out = os.path.join(self.tmp, 'e4_call.py')
        self.assertTrue(os.path.isfile(out))
        self.assertIn(b'WROTE', p.stdout)
        with io.open(out, 'r', encoding='utf-8') as fh:
            src = fh.read()
        self.assertFalse(src.startswith(u'\ufeff'))  # UTF-8 no BOM
        self.assertIn(u'请回答三个问题', src)

    def test_custom_timeout_rendered(self):
        body = self._write('body.txt', u'叙事。')
        out = os.path.join(self.tmp, 'nested', 'dir', 'e4_call.py')
        p = _run_cli('--body', body, '--label', 'L', '--out', out,
                     '--timeout', '300')
        self.assertEqual(p.returncode, 0, p.stdout.decode('utf-8', 'replace'))
        self.assertTrue(os.path.isfile(out))  # parent auto-created
        with io.open(out, 'r', encoding='utf-8') as fh:
            self.assertIn('TIMEOUT = 300', fh.read())

    def test_questions_file_override(self):
        body = self._write('body.txt', u'叙事。')
        qf = self._write('custom_q.txt', u'请回答三个问题（自定义形态）：\n1) Q1？')
        out = os.path.join(self.tmp, 'e4_call.py')
        p = _run_cli('--body', body, '--label', 'L', '--out', out,
                     '--questions-file', qf)
        self.assertEqual(p.returncode, 0, p.stdout.decode('utf-8', 'replace'))
        with io.open(out, 'r', encoding='utf-8') as fh:
            src = fh.read()
        self.assertIn(u'请回答三个问题（自定义形态）', src)
        self.assertNotIn(u'指出原句', src)  # canonical absent

    def test_rc2_missing_body(self):
        p = _run_cli('--body', os.path.join(self.tmp, 'nope.txt'),
                     '--label', 'L')
        self.assertEqual(p.returncode, 2)

    def test_rc2_empty_body(self):
        body = self._write('empty.txt', '   \n')
        p = _run_cli('--body', body, '--label', 'L')
        self.assertEqual(p.returncode, 2)

    def test_rc2_body_already_has_questions(self):
        body = self._write('dup.txt', u'叙事。请回答三个问题 误嵌')
        p = _run_cli('--body', body, '--label', 'L')
        self.assertEqual(p.returncode, 2)
        self.assertIn(b'question block', p.stdout)

    def test_rc2_bad_timeout(self):
        body = self._write('body.txt', u'叙事。')
        p = _run_cli('--body', body, '--label', 'L', '--timeout', '0')
        self.assertEqual(p.returncode, 2)

    def test_rc2_missing_questions_file(self):
        body = self._write('body.txt', u'叙事。')
        p = _run_cli('--body', body, '--label', 'L',
                     '--questions-file', os.path.join(self.tmp, 'noq.txt'))
        self.assertEqual(p.returncode, 2)

    def test_rc2_out_is_dir(self):
        body = self._write('body.txt', u'叙事。')
        p = _run_cli('--body', body, '--label', 'L', '--out', self.tmp)
        self.assertEqual(p.returncode, 2)

    def test_no_writes_on_usage_error(self):
        body = self._write('badbody.txt', u'叙事。请回答三个问题 误嵌')
        before = sorted(os.listdir(self.tmp))
        _run_cli('--body', body, '--label', 'L')
        self.assertEqual(sorted(os.listdir(self.tmp)), before)


